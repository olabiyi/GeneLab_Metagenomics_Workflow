#!/usr/bin/env python3

import argparse
import json
import os
import sys
from zipfile import BadZipFile, ZipFile
import pandas as pd

# Example usage:
# Illumina low biomass samples with raw fastq and human reads removed summary multiqc zip file provided
# generate_reads_statistics.py --sample-type low_biomass --filtered filtered_multiqc_report.zip --blank-removed decontam_multiqc_report.zip --technology illumina --raw raw_multiqc_report.zip --human-removed HRrm_multiqc_report.zip
# Illumina standard samples with raw fastq and human reads removed summary multiqc zip file provided
# generate_reads_statistics.py --sample-type standard --filtered filtered_multiqc_report.zip  --technology illumina --raw raw_multiqc_report.zip --human-removed HRrm_multiqc_report.zip
# Illumina with human removed summary file precompiled
# generate_reads_statistics.py --sample-type low_biomass --filtered filtered_multiqc_report.zip --blank-removed decontam_multiqc_report.zip --technology illumina --human-removed-summary human_removed_summary.tsv
# Illumina standard samples with human removed summary file precompiled
# generate_reads_statistics.py --sample-type standard --filtered filtered_multiqc_report.zip --technology illumina --human-removed-summary human_removed_summary.tsv
# Nanopore
# Nanopore low biomass samples
# generate_reads_statistics.py --sample-type low_biomass --filtered filtered_multiqc_report.zip --blank-removed decontam_multiqc_report.zip --technology nanopore --raw raw_multiqc_report.zip --human-removed HRrm_multiqc_report.zip --trimmed trimmed_multiqc_report.zip
# Nanopore standard samples
# generate_reads_statistics.py --sample-type standard --filtered filtered_multiqc_report.zip  --technology nanopore --raw raw_multiqc_report.zip --human-removed HRrm_multiqc_report.zip --trimmed trimmed_multiqc_report.zip

parser = argparse.ArgumentParser(description = "This program generates read statistics from MultiQC reports generated by GeneLab's Metagenomics pipelines.", 
                                 usage="%(prog)s --sample-type <low_biomass/standard> --filtered <filtered_multiqc_report.zip> --blank-removed <decontam_multiqc_report.zip> \
                                    --technology <illumina/nanopore> [--raw <raw_multiqc_report.zip>] [--human-removed <HRrm_multiqc_report.zip>] \
                                        [--trimmed <trimmed_multiqc_report.zip>] [-r/--human-removed-summary <human_removed_summary.tsv>] \
                                            [--host-removed <HostRm_multiqc_report.zip>] [--output <output_file.tsv>]")
required = parser.add_argument_group('required arguments')

required.add_argument("--filtered", default="",
                    help='Path to the filtered MultiQC report zip file. e.g., "filtered_multiqc_report.zip" (default: ""). \
                        This is the zip generated after running multiqc on the outputs of FastP and Filtlong for the illumina \
                            and nanopore pipelines, respectively.', action="store", required=True)
required.add_argument("--technology", default="nanopore",
                    help='Technology used for sequencing. One of "illumina" or "nanopore" (default: "nanopore")',
                    choices=["illumina", "nanopore"], action="store", required=True)
required.add_argument("--sample-type", default="low_biomass",
                    help='Sample type sequenced. One of "low_biomass" or "standard" (default: "low_biomass")', choices=["low_biomass", "standard"], action="store", required=True)
parser.add_argument("--blank-removed", default="",
                    help='Path to the blank removed MultiQC report zip file. e.g., "decontam_multiqc_report.zip" (default: ""). \
                          Required only if --sample-type is low_biomass', action="store")
parser.add_argument("--raw", default="",
                    help='Path to the raw reads MultiQC report zip file. e.g., "raw_multiqc_GLlbnMetag_report.zip" (default: ""). \
                        Not required when --human-removed-summary is provided and technology is "illumina"', action="store")
parser.add_argument("--human-removed", default="",
                    help='Path to the human reads removed MultiQC report zip file. e.g., "HRrm_multiqc_report.zip" (default: ""). \
                        Not required when --human-removed-summary is provided and technology is "illumina"', action="store")
parser.add_argument("--host-removed", default="",
                    help='Path to the host reads removed MultiQC report zip file. e.g., "HostRm_multiqc_report.zip" (default: ""). \
                        Only required when additional host (not human) reads are removed', action="store")
parser.add_argument("--trimmed", default="",
                    help='Path to the trimmed MultiQC report zip file generated when running the nanopore pipeline. e.g., "trimmed_multiqc_report.zip" (default: ""). \
                        Only required when --technology is "nanopore"', action="store")
parser.add_argument("--human-removed-summary", help = "Path to the human reads removed summary file.", action = "store")
parser.add_argument("--output", default="reads_statistics.tsv", help="Path to the output file. (default: reads_statistics.tsv)", action="store")



if len(sys.argv)==1:
    parser.print_help(sys.stderr)
    sys.exit(0)

args = parser.parse_args()

def find_multiqc_json_from_zip(zf):
    for name in zf.namelist():
        if os.path.basename(name) == "multiqc_data.json":
            return name
    return None


def load_json_from_path(path):
    try:
        with ZipFile(path, "r") as zf:
            name = find_multiqc_json_from_zip(zf)
            if not name:
                raise FileNotFoundError("No multiqc_data.json found in zip")
            with zf.open(name) as fh:
                return json.load(fh)
    except BadZipFile as exc:
        raise RuntimeError(f"Invalid zip file: {path}") from exc

def get_read_count(stage, zip_file, technology):
    if technology == "nanopore":
        read_count_key = "Number of reads_fastq"
        reads_stats = load_json_from_path(zip_file)["report_saved_raw_data"]["multiqc_nanostat"]
    else:
        read_count_key = "total_sequences"
        reads_stats = load_json_from_path(zip_file)["report_general_stats_data"][0]
    
    data = {"Sample_ID":[], stage: []}
    for k,v in reads_stats.items():
        data["Sample_ID"].append(k)
        data[stage].append(v[read_count_key])
        
    # Dataframe from dictionary
    df = pd.DataFrame(data)
    # Delete unwanted suffix in sample names
    pattern = r'(_(raw|HRremoved_raw|filtered|trimmed|decontam|HRrm|HostRm))?_R\d+$'
    df.Sample_ID = df.Sample_ID.str.replace(pattern, '', regex=True)
    df.drop_duplicates(inplace=True)
    return(df)

def main():
    
    if args.technology == "nanopore":
        zip_file_dict = {"Human-removed": args.human_removed,
                         "Filtered": args.filtered, 
                         "Trimmed": args.trimmed}    
        df =  get_read_count(stage="Raw", zip_file=args.raw, technology=args.technology)

    # Illumina with human removed summary file precompiled    
    elif args.human_removed_summary != "":
        zip_file_dict = {"Filtered-trimmed": args.filtered}
        colnames = ["Sample_ID", "Raw", "Human-removed", "Percent_human_reads_removed"]
        df = pd.read_csv(args.human_removed_summary, delimiter="\t")
        df.columns = colnames
        
    # Illumina with raw fastq and human reads removed summary multiqc zip file provided   
    else:
        zip_file_dict = {"Human-removed": args.human_removed, "Filtered-trimmed": args.filtered}
        df =  get_read_count(stage="Raw", zip_file=args.raw, technology=args.technology)

    if args.sample_type == "low_biomass":
        zip_file_dict["Blank-removed"] = args.blank_removed

    if args.host_removed != "":
        zip_file_dict["Host-removed"] = args.host_removed

    for stage, zip_file in zip_file_dict.items():
        df2 = get_read_count(stage, zip_file, technology=args.technology)
        df = df.merge(df2, how="left", on="Sample_ID")
        
    # Calculate percentages
    if args.technology == "nanopore":
        df['Percent_reads_filtered'] = ((df['Raw'] - df['Filtered'])/df['Raw']) * 100
        df['Percent_reads_trimmed'] = ((df['Filtered'] - df['Trimmed'])/df['Filtered']) * 100
        df['Percent_human_reads_removed'] = ((df['Trimmed'] - df['Human-removed'])/df['Trimmed']) * 100
        if args.sample_type == "low_biomass":
            df['Percent_blank_reads_removed'] = ((df['Human-removed'] - df['Blank-removed'])/df['Human-removed']) * 100

    # Illumina with human removed summary file precompiled    
    elif args.human_removed_summary != "":
        df['Percent_reads_filtered-trimmed'] = ((df['Human-removed'] - df['Filtered-trimmed'])/df['Human-removed']) * 100
        if args.sample_type == "low_biomass":
            df['Percent_blank_reads_removed'] = ((df['Filtered-trimmed'] - df['Blank-removed'])/df['Filtered-trimmed']) * 100
        
    # Illumina with raw fastq and human reads removed summary multiqc zip file provided
    else:
        df['Percent_human_reads_removed'] = ((df['Raw'] - df['Human-removed'])/df['Raw']) * 100
        df['Percent_reads_filtered-trimmed'] = ((df['Human-removed'] - df['Filtered-trimmed'])/df['Human-removed']) * 100
        if args.sample_type == "low_biomass":
            df['Percent_blank_reads_removed'] = ((df['Filtered-trimmed'] - df['Blank-removed'])/df['Filtered-trimmed']) * 100

    # Calculate percent host reads removed if host removed data is provided    
    if args.host_removed != "" and args.sample_type == "low_biomass":
        df['Percent_host_reads_removed'] = ((df['Blank-removed'] - df['Host-removed'])/df['Blank-removed']) * 100
    elif args.host_removed != "" and args.sample_type == "standard" and args.technology == "nanopore":
        df['Percent_host_reads_removed'] = ((df['Trimmed'] - df['Host-removed'])/df['Trimmed']) * 100
    elif args.host_removed != "" and args.sample_type == "standard" and args.technology == "illumina":
        df['Percent_host_reads_removed'] = ((df['Filtered-trimmed'] - df['Host-removed'])/df['Filtered-trimmed']) * 100

    column_order = ['Sample_ID', 'Raw', 'Human-removed', 'Filtered-trimmed', 
                    'Percent_human_reads_removed', 'Percent_reads_filtered-trimmed']
    # Define column order for output file based on technology and whether host removed data is provided
    if args.technology == "nanopore":
        # Host removed data is provided and sample type is low biomass
        if args.host_removed != "" and args.sample_type == "low_biomass":
            column_order = ['Sample_ID', 'Raw', 'Filtered', 'Trimmed', 'Human-removed',
                            'Blank-removed', 'Host-removed',  'Percent_reads_filtered', 'Percent_reads_trimmed',
                            'Percent_human_reads_removed', 'Percent_blank_reads_removed', 'Percent_host_reads_removed']
        # Host removed data is not provided and sample type is low biomass
        elif args.host_removed == "" and args.sample_type == "low_biomass":
            column_order = ['Sample_ID', 'Raw',  'Filtered', 'Trimmed', 'Human-removed',
                            'Blank-removed', 'Percent_reads_filtered', 'Percent_reads_trimmed', 
                            'Percent_human_reads_removed', 'Percent_blank_reads_removed']
        # Host removed data is not provided and sample type is standard
        elif args.host_removed == "" and args.sample_type == "standard":
            column_order = ['Sample_ID', 'Raw', 'Filtered', 'Trimmed', 'Human-removed',
                            'Percent_reads_filtered', 'Percent_reads_trimmed', 'Percent_human_reads_removed']
        # Host removed data is provided and sample type is standard
        else:   
            column_order = ['Sample_ID', 'Raw',  'Filtered', 'Trimmed', 'Human-removed',
                            'Host-removed',  'Percent_reads_filtered', 'Percent_reads_trimmed',
                            'Percent_human_reads_removed', 'Percent_host_reads_removed']

    # Define column order for output file based on technology and whether host removed data is provided for illumina
    if args.technology == "illumina":
        # Host removed data is provided and sample type is low biomass
        if args.host_removed != "" and args.sample_type == "low_biomass":
            column_order = ['Sample_ID', 'Raw', 'Human-removed', 'Filtered-trimmed', 'Blank-removed', 'Host-removed',
                            'Percent_human_reads_removed', 'Percent_reads_filtered-trimmed', 
                            'Percent_blank_reads_removed', 'Percent_host_reads_removed']
        # Host removed data is not provided and sample type is low biomass
        elif args.host_removed == "" and args.sample_type == "low_biomass":
            column_order = ['Sample_ID', 'Raw', 'Human-removed', 'Filtered-trimmed', 'Blank-removed',
                            'Percent_human_reads_removed', 'Percent_reads_filtered-trimmed', 
                            'Percent_blank_reads_removed']
        # Host removed data is not provided and sample type is standard
        elif args.host_removed == "" and args.sample_type == "standard":
            column_order = ['Sample_ID', 'Raw', 'Human-removed', 'Filtered-trimmed', 
                            'Percent_human_reads_removed', 'Percent_reads_filtered-trimmed']
        # Host removed data is provided and sample type is standard 
        else:   
            column_order = ['Sample_ID', 'Raw', 'Human-removed', 'Filtered-trimmed', 'Host-removed',
                            'Percent_human_reads_removed', 'Percent_reads_filtered-trimmed', 'Percent_host_reads_removed']

    
    # Order columns as expected 
    df = df[column_order]
   
    # Convert counts to integers and percentages to 2 decimal places
    for col in df.columns:
        if col.startswith("Percent"):
            na_mask = df[col].notnull()
            df.loc[na_mask, col] = df.loc[na_mask, col].astype(float).round(2)
        elif col != "Sample_ID":
            na_mask = df[col].notnull()
            df.loc[na_mask, col] = df.loc[na_mask, col].astype(int)

    # Save output file
    df.to_csv(args.output, sep="\t", index=False)
    
if __name__ == "__main__":
    main()
